X_train_kmeans, X_test_kmeans, y_train_kmeans, y_test_kmeans = train_test_split(
    X_kmeans,
    df_clean['Disease_Type'],
    test_size=0.30,
    random_state=42,
    stratify=df_clean['Disease_Type']
)

kmeans_scaler = StandardScaler()

X_train_kmeans_scaled = kmeans_scaler.fit_transform(X_train_kmeans)
X_test_kmeans_scaled = kmeans_scaler.transform(X_test_kmeans)

print("K-Means data scaled successfully.")

# =========================
# ELBOW METHOD
# =========================

inertias = []

K_range = range(2, 11)

for k in K_range:

    model = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    model.fit(X_train_kmeans_scaled)

    inertias.append(model.inertia_)


plt.figure(figsize=(8, 5))

plt.plot(
    K_range,
    inertias,
    marker='o'
)

plt.xlabel("Number of Clusters (K)")
plt.ylabel("Inertia")
plt.title("Elbow Method for K-Means")
plt.grid()

plt.show()

# =========================
# TRAIN K-MEANS
# =========================

kmeans = KMeans(
    n_clusters=2,
    random_state=42,
    n_init=10
)

kmeans.fit(X_train_kmeans_scaled)

cluster_train = kmeans.labels_
cluster_test = kmeans.predict(X_test_kmeans_scaled)

print("K-Means clustering completed.")

# =========================
# SILHOUETTE SCORE
# =========================

silhouette_train = silhouette_score(
    X_train_kmeans_scaled,
    cluster_train
)

silhouette_test = silhouette_score(
    X_test_kmeans_scaled,
    cluster_test
)

print("Training Silhouette Score:", round(silhouette_train, 4))
print("Testing Silhouette Score :", round(silhouette_test, 4))

# =========================
# MAP K-MEANS CLUSTERS TO CLASS LABELS
# =========================

# Use the encoded training labels: 0, 1, 2
cm_train = confusion_matrix(
    y_train,
    cluster_train
)

row_ind, col_ind = linear_sum_assignment(-cm_train)

cluster_mapping = {
    cluster: class_label
    for class_label, cluster in zip(row_ind, col_ind)
}

print("Cluster mapping:")
print(cluster_mapping)

# =========================
# K-MEANS PREDICTED CLASSES
# =========================

y_pred_kmeans = np.array([
    cluster_mapping[cluster]
    for cluster in cluster_test
])

print("K-Means class predictions generated.")

# =========================
